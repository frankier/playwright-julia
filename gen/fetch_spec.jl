#!/usr/bin/env julia
#
# Vendor Playwright's protocol spec into protocol/spec/.
#
#     julia --project=gen gen/fetch_spec.jl
#
# The spec is the input to gen/generate.jl. It is NOT shipped in the
# playwright-core npm tarball (only CDP's protocol.d.ts is), so it comes from
# the microsoft/playwright repo at tag v$PLAYWRIGHT_VERSION — where
# PLAYWRIGHT_VERSION is read from src/driver.jl, the single place the version
# is written. Vendoring keeps builds and CI off the network and makes protocol
# changes reviewable as a diff.
#
# Re-running is idempotent. The download is staged in a temporary directory and
# swapped into place only once every file has arrived, so an interrupted or
# failed fetch never leaves a partial protocol/spec/ behind.

using Downloads
using JSON3

const REPO_ROOT = dirname(@__DIR__)
const PROTOCOL_DIR = joinpath(REPO_ROOT, "protocol")
const SPEC_SUBPATH = "packages/protocol/spec"

"""
    playwright_version() -> String

The pinned Playwright version, parsed out of `src/driver.jl` rather than
re-typed here. `PLAYWRIGHT_VERSION` stays the single source of truth.
"""
function playwright_version()
    driver = joinpath(REPO_ROOT, "src", "driver.jl")
    m = match(r"^const PLAYWRIGHT_VERSION = \"([^\"]+)\""m, read(driver, String))
    m === nothing && error("could not find PLAYWRIGHT_VERSION in $driver")
    return m.captures[1]
end

"""
    spec_listing(tag) -> Vector{@NamedTuple{name::String, url::String}}

The `*.yml` files in the protocol spec directory at `tag`, via the GitHub
contents API. Errors mention the tag, because a non-existent version is the
overwhelmingly likely cause of a failure here.
"""
function spec_listing(tag::AbstractString)
    url = "https://api.github.com/repos/microsoft/playwright/contents/$SPEC_SUBPATH?ref=$tag"
    body = try
        sprint(io -> Downloads.download(url, io))
    catch err
        error("""
              could not list the protocol spec at tag $tag.

              Tried: $url
              Cause: $(sprint(showerror, err))

              Check that $tag is a real microsoft/playwright release tag (the
              version comes from PLAYWRIGHT_VERSION in src/driver.jl). Nothing
              under protocol/ has been modified.
              """)
    end
    entries = JSON3.read(body)
    files = [
        (name = String(e.name), url = String(e.download_url)) for
        e in entries if e.type == "file" && endswith(String(e.name), ".yml")
    ]
    isempty(files) && error("no .yml files found at $SPEC_SUBPATH for tag $tag")
    return sort!(files; by = f -> f.name)
end

readme_text(version, files) = """
    # Vendored Playwright protocol spec

    **Generated by `gen/fetch_spec.jl` — do not edit by hand.**

    `spec/` is a verbatim copy of `$SPEC_SUBPATH` from
    [microsoft/playwright](https://github.com/microsoft/playwright) at tag
    `v$version`, the version pinned by `PLAYWRIGHT_VERSION` in `src/driver.jl`.
    It is the input to `gen/generate.jl`, which emits
    `src/generated/channels.jl`.

    It is vendored rather than fetched on demand so that builds, tests and CI
    never depend on GitHub, and so protocol changes show up as a reviewable
    diff. These files are Microsoft's, licensed Apache 2.0 — see
    `LICENSE-PLAYWRIGHT`.

    ## Refreshing

    Change `PLAYWRIGHT_VERSION` in `src/driver.jl`, then:

    ```
    julia --project=gen gen/fetch_spec.jl   # re-vendor protocol/spec/
    julia --project=gen gen/generate.jl     # regenerate src/generated/channels.jl
    ```

    ## Contents

    $version ($(length(files)) files): $(join(sort([f.name for f in files]), ", "))
    """

function fetch_spec(; version::AbstractString = playwright_version())
    tag = "v$version"
    files = spec_listing(tag)
    @info "Vendoring Playwright protocol spec" tag files = length(files)

    license_url = "https://raw.githubusercontent.com/microsoft/playwright/$tag/LICENSE"

    # Stage everything under protocol/ so the final swap is a same-filesystem
    # rename, then publish only once all downloads have succeeded.
    staging = mktempdir(REPO_ROOT)
    try
        specdir = joinpath(staging, "spec")
        mkpath(specdir)
        for f in files
            Downloads.download(f.url, joinpath(specdir, f.name))
        end
        Downloads.download(license_url, joinpath(staging, "LICENSE-PLAYWRIGHT"))
        write(joinpath(staging, "VERSION"), version * "\n")
        write(joinpath(staging, "README.md"), readme_text(version, files))

        rm(PROTOCOL_DIR; recursive = true, force = true)
        mv(staging, PROTOCOL_DIR)
    catch
        rm(staging; recursive = true, force = true)
        rethrow()
    end

    @info "Protocol spec vendored" dir = PROTOCOL_DIR version
    return PROTOCOL_DIR
end

abspath(PROGRAM_FILE) == abspath(@__FILE__) && fetch_spec()
